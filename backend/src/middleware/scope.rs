/// Compound scope: search + queue:write. Auto-season search triggers downloads,
/// which needs both; a single-scope check would not suffice. Checking both here
/// avoids a confusing 403 for whichever scope happened to be checked first.
pub async fn search_and_queue_write(req: Request, next: Next) -> Response {
    let Some(granted) = req.extensions().get::<Vec<ApiScope>>().cloned() else {
        return unauthorized();
    };

    let required = [ApiScope::Search, ApiScope::QueueWrite];
    if required
        .iter()
        .all(|need| granted.iter().any(|have| have.permits(*need)))
    {
        next.run(req).await
    } else {
        insufficient_scope(&required, &granted)
    }
}
